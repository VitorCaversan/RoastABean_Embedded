extern void SpiConfig_configureSpiBus(void)
{
    spi_bus_config_t cfg =
    {
        .mosi_io_num = -1,
        .miso_io_num = GPIO_NUM_15,
        .sclk_io_num = GPIO_NUM_1,
        .quadwp_io_num = -1,
        .quadhd_io_num = -1,
        .max_transfer_sz = 0,
        .flags = 0
    };
    ESP_ERROR_CHECK(spi_bus_initialize(HELPER_SPI_HOST_DEFAULT, &cfg, 1));
}

