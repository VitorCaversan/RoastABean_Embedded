/*******************************************************************************
 * INCLUDES
 ******************************************************************************/
#include "SpiConfig.h"

/*******************************************************************************
 * MACROS AND DEFINES
 ******************************************************************************/

#define PIN_SCLK     GPIO_NUM_2
#define PIN_MOSI     GPIO_NUM_15
#define PIN_MISO     GPIO_NUM_35

/*******************************************************************************
 * LOCAL FUNCTION DECLARATIONS
 ******************************************************************************/

/*******************************************************************************
 * LOCAL VARIABLES
 ******************************************************************************/

static const char *TAG = "SPI_CONFIG";

/*******************************************************************************
 * EXTERNAL FUNCTIONS
 ******************************************************************************/

extern void spiConfig_configureSpiBus(void)
{
    spi_bus_config_t busConfig = {
        .sclk_io_num = PIN_SCLK,
        .mosi_io_num = PIN_MOSI,
        .miso_io_num = PIN_MISO,
        .quadwp_io_num = -1,
        .quadhd_io_num = -1,
        .max_transfer_sz = LCD_H_RES_IN_PIX * 80 * sizeof(uint16_t),
    };
    ESP_ERROR_CHECK(spi_bus_initialize(DEFAULT_SPI_HOST, &busConfig, SPI_DMA_CH_AUTO));

    ESP_LOGI(TAG, "Created SPI bus");
}

